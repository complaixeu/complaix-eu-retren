#!/usr/bin/env bash
# scripts/local-env.sh — write .env.local pointing the app at the LOCAL Supabase.
# Run after `pnpm db:start`. The keys are the CLI's fixed local-development keys,
# not DEV/remote secrets; .env.local is gitignored anyway. Values are not printed.
set -euo pipefail
cd "$(dirname "$0")/.."

status="$(pnpm exec supabase status -o json)" || { echo "Local Supabase not running: pnpm db:start" >&2; exit 1; }
api_url="$(jq -r '.API_URL // empty' <<<"$status")"
anon_key="$(jq -r '.ANON_KEY // .PUBLISHABLE_KEY // empty' <<<"$status")"
service_key="$(jq -r '.SERVICE_ROLE_KEY // .SECRET_KEY // empty' <<<"$status")"
[ -n "$api_url" ] && [ -n "$anon_key" ] && [ -n "$service_key" ] || { echo "supabase status incomplete" >&2; exit 1; }

if [ -e .env.local ] && ! grep -q '^# generated by scripts/local-env.sh' .env.local; then
  echo ".env.local exists and was not generated by this script; not overwriting." >&2
  exit 1
fi

umask 077
cat > .env.local <<EOF
# generated by scripts/local-env.sh — LOCAL Supabase only
NEXT_PUBLIC_SUPABASE_URL=$api_url
NEXT_PUBLIC_SUPABASE_ANON_KEY=$anon_key
SUPABASE_SERVICE_ROLE_KEY=$service_key
NEXT_PUBLIC_APP_URL=http://localhost:${APP_PORT:-3100}
EOF
echo "Wrote .env.local for $api_url"
